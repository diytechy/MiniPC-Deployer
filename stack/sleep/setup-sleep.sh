#!/usr/bin/env bash
# setup-sleep.sh - install the sleep feeder's unit and timer.
#
# Idempotent and non-interactive, like every other setup script here. It is meant
# to be called from firstboot only when SLEEP_ENABLED=true; on a box where the
# knob is false it does nothing at all, and nothing it would have installed
# exists. That is the whole of "gated, OFF by default" for a service that is not
# a container: there is no compose profile to join, so the knob IS the gate -
# exactly as for AI_USAGE_ENABLED and WEIGHT_ENABLED.
#
# IT CREATES THE ACCOUNT, with NO HOME. The feeder holds no credential file: the
# myAir password arrives through EnvironmentFile= (MYAIR_PASSWORD, from the
# secret store through the materialiser) and the sign-in tokens live in memory
# for one cycle. The only thing it writes is its state directory, which systemd
# creates and owns (StateDirectory=homehub-sleep, mode 0700).
#
# THE ACCOUNT NAME IS THE ONE SYSTEMD USES. It is written into a drop-in from
# SLEEP_USER_ACCOUNT (the construction setup-weight.sh and setup-ai-usage.sh
# arrived at after the 2026-09-09 cross-review), so a knob nobody read cannot
# diverge from a unit nobody edited.
#
# NEITHER MYAIR VALUE IS EVER PRINTED OR KEPT. This script only asks whether
# MYAIR_EMAIL and MYAIR_PASSWORD are non-blank, and says so without echoing them.
#
# Adds NO apt package: python3 stdlib only (zoneinfo needs python3 >= 3.9 and the
# system tz database, both of which the hub's Ubuntu has). No apt export is owed.
#
# Usage: setup-sleep.sh [--check-only | --emit-dropin DIR]
# Exit 0 = converged (or disabled). 1 = failed. 2 = refused.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="${SLEEP_ENV_FILE:-$HERE/../.env}"
UNIT_DIR="${SLEEP_UNIT_DIR:-/etc/systemd/system}"
DROPIN_DIR="$UNIT_DIR/homehub-sleep.service.d"
MODE="${1:-}"

SLEEP_ENABLED="${SLEEP_ENABLED:-false}"
SLEEP_USER="${SLEEP_USER:-}"
SLEEP_USER_ACCOUNT="${SLEEP_USER_ACCOUNT:-homehub-sleep}"
SLEEP_FEED_URL="${SLEEP_FEED_URL:-}"

# MUST STAY EQUAL TO THE UNIT'S StateDirectory=. The account-name knob cannot
# move it, so it is a constant, and tests/test_sleep_deploy.py asserts this
# string and the unit's StateDirectory= still agree.
SLEEP_STATE_DIR=/var/lib/homehub-sleep

# Value of KEY in the .env, quotes stripped; empty when absent. Used ONLY for the
# SLEEP_* knobs. The myAir pair goes through env_present below and is never held.
env_get() {
    local value
    value="$(grep -E "^$1=" "$ENV_FILE" 2>/dev/null | tail -1 | cut -d= -f2- || true)"
    # ONE rule, shared with firstboot.sh and apply-env-lines.py: strip a single
    # MATCHING pair of surrounding quotes (double or single) and nothing else. A lone
    # leading or trailing quote, or a quote inside the value, is left in place, so
    # 'true and tr'ue are not "true" here, exactly as in the other two parsers.
    case "$value" in
        \"?*\") value="${value#\"}"; value="${value%\"}" ;;
        \'?*\') value="${value#\'}"; value="${value%\'}" ;;
        \"\"|\'\') value="" ;;
    esac
    printf '%s' "$value"
}

# 0 if KEY has a non-blank value in the .env. Never prints, never stores it.
env_present() {
    [ -f "$ENV_FILE" ] || return 1
    local value
    value="$(grep -E "^$1=" "$ENV_FILE" 2>/dev/null | tail -1 | cut -d= -f2- || true)"
    case "$value" in      # the same single-matching-pair rule as env_get
        \"?*\") value="${value#\"}"; value="${value%\"}" ;;
        \'?*\') value="${value#\'}"; value="${value%\'}" ;;
        \"\"|\'\') value="" ;;
    esac
    [ -n "$(printf '%s' "$value" | tr -d '[:space:]')" ]
}

if [ -f "$ENV_FILE" ]; then
    # Read only the keys we own, and never `source` a file that holds secrets.
    for key in SLEEP_ENABLED SLEEP_USER SLEEP_USER_ACCOUNT SLEEP_FEED_URL; do
        value="$(env_get "$key")"
        [ -n "$value" ] && printf -v "$key" '%s' "$value"
    done
fi

say() { printf '%s\n' "$*"; }
refuse() { say "REFUSED: $*"; exit 2; }

# ── THE DROP-IN: THE ACCOUNT THE UNIT RUNS AS ───────────────────────────────
# Writes the generated piece into $1 (in production, the unit's drop-in
# directory). Split out so a test can run it and READ what it wrote, rather than
# grepping this script and believing a string.
emit_dropin() {
    local dir="$1"
    install -d -m 0755 "$dir"
    cat > "$dir/10-account.conf" <<EOF
# GENERATED by setup-sleep.sh from SLEEP_USER_ACCOUNT. Do not hand-edit: the
# account certified and the account systemd runs must be one value.
[Service]
User=$SLEEP_USER_ACCOUNT
Group=$SLEEP_USER_ACCOUNT
EOF
    chmod 0644 "$dir/10-account.conf"
}

if [ "$SLEEP_ENABLED" != "true" ] && [ "$MODE" != "--emit-dropin" ]; then
    say "SLEEP_ENABLED is not true - the sleep feeder is not installed."
    exit 0
fi

# ── REFUSING TO GUESS THE IDENTITY ──────────────────────────────────────────
# Blank is not "the only user" and it is not "all users". A sleep score is a
# private health measurement, and the wrong board is a stranger's wall. The
# feeder refuses too (resolve_identity); this is the early, legible copy.
[ -n "$SLEEP_USER" ] || refuse \
    "SLEEP_USER is blank. The feeder posts for ONE explicit identity (the stable
    Google \`sub\`, the same value as NAGLIGHT_USER) and will not guess whose
    sleep this is."

[ -n "$SLEEP_FEED_URL" ] || refuse \
    "SLEEP_FEED_URL is blank. There is no default - the tracker is bridge-only,
    so the right value depends on this box."

case "$SLEEP_USER_ACCOUNT" in
    hub|root) refuse "SLEEP_USER_ACCOUNT=$SLEEP_USER_ACCOUNT. \`hub\` carries
        (ALL) NOPASSWD: ALL and root needs no explanation; the feeder runs as a
        dedicated unprivileged account with nothing else in it." ;;
esac

# ── THE SIGN-IN MUST BE CONFIGURED, BUT ITS VALUES ARE NOT OURS TO READ ─────
env_present MYAIR_EMAIL || refuse \
    "MYAIR_EMAIL is blank in $ENV_FILE. It comes from the identity table
    (household.MyAirEmail) through the materialiser; re-materialise the .env."
env_present MYAIR_PASSWORD || refuse \
    "MYAIR_PASSWORD is blank in $ENV_FILE. It comes from the secret store (key
    MyAirPassword) through the materialiser; import the key, then re-materialise."

# ── IS THERE A CLOCK-SYNCHRONISATION SIGNAL? ────────────────────────────────
# The feeder refuses to publish a timestamped score unless the host clock is shown
# synchronised: systemd-timesyncd's flag file, else `timedatectl show -p
# NTPSynchronized`. On a hub with NEITHER it publishes the grey (unavailable) gauge
# for ever - correct, but not what anyone wants - so say so now, at install time.
# One line, never fatal. SLEEP_SYNC_FLAG and SLEEP_TIMEDATECTL exist so a test can
# point them elsewhere.
probe_clock_sync() {
    local flag="${SLEEP_SYNC_FLAG:-/run/systemd/timesync/synchronized}" answer=""
    local td="${SLEEP_TIMEDATECTL:-timedatectl}"
    if [ -e "$flag" ]; then
        say "clock sync: $flag is present - systemd-timesyncd reports the clock synchronised."
        return 0
    fi
    if command -v "$td" >/dev/null 2>&1; then
        if command -v timeout >/dev/null 2>&1; then
            answer="$(timeout 5 "$td" show -p NTPSynchronized --value 2>/dev/null || true)"
        else
            answer="$("$td" show -p NTPSynchronized --value 2>/dev/null || true)"
        fi
        case "$answer" in
            yes) say "clock sync: timedatectl reports NTPSynchronized=yes (the flag file $flag is absent)."; return 0 ;;
            no)  say "clock sync: timedatectl reports NTPSynchronized=no - the sleep gauge will show grey until the clock synchronises; check systemd-timesyncd."; return 0 ;;
        esac
    fi
    say "WARNING clock sync: neither $flag nor 'timedatectl show -p NTPSynchronized' is available - the feeder cannot tell the clock is set and will publish only the grey (unavailable) gauge. Install or enable systemd-timesyncd."
}

if [ "$MODE" = "--check-only" ]; then
    say "check-only: identity set, destination set, myAir sign-in configured."
    probe_clock_sync
    exit 0
fi

# `--emit-dropin DIR` writes only the generated drop-in and stops. No root, no
# install: it exists so a test can assert that the account really is derived
# from the knob.
if [ "$MODE" = "--emit-dropin" ]; then
    [ -n "${2:-}" ] || refuse "--emit-dropin needs a directory"
    emit_dropin "$2"
    exit 0
fi

probe_clock_sync

if ! id -u "$SLEEP_USER_ACCOUNT" >/dev/null 2>&1; then
    # --system, no shell, no password, NO HOME: it owns nothing but its state.
    useradd --system --no-create-home --shell /usr/sbin/nologin "$SLEEP_USER_ACCOUNT"
    say "created system account $SLEEP_USER_ACCOUNT (no shell, no password, no home)."
fi

install -d -m 0755 "$UNIT_DIR"
install -m 0644 "$HERE/homehub-sleep.service" "$UNIT_DIR/homehub-sleep.service"
install -m 0644 "$HERE/homehub-sleep.timer"   "$UNIT_DIR/homehub-sleep.timer"

# The state directory is created by systemd (StateDirectory=), but a hand-run of
# the feeder before the first timer tick needs it to exist and to be the
# account's own, 0700. The score lives in a file inside it.
install -d -m 0700 -o "$SLEEP_USER_ACCOUNT" -g "$SLEEP_USER_ACCOUNT" "$SLEEP_STATE_DIR"

emit_dropin "$DROPIN_DIR"

if command -v systemctl >/dev/null 2>&1; then
    systemctl daemon-reload
    # The TIMER is enabled, never the service: enabling a oneshot service means
    # one run at boot and none after it, which is the classic way a feeder ends
    # up posting a single reading and then going quietly stale forever.
    systemctl enable --now homehub-sleep.timer
fi

say "sleep feeder installed; runs as $SLEEP_USER_ACCOUNT every 30 minutes."
say "STILL OWED BY A HUMAN if the gauge stays grey:"
say "  * journalctl -u homehub-sleep names the cause. 'authentication failure'"
say "    means myAir refused the sign-in; 'asks for an emailed code' means a"
say "    person must sign in to myAir (the refresh-gauge-logins skill has the"
say "    procedure). Until then the gauge reads 'unavailable', which is correct."
exit 0
