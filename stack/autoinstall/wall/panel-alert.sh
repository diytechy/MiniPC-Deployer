#!/usr/bin/env bash
# panel-alert - the wall panel's alert route to the hub (SR-094 / LLR-1188).
#
# Installed by wall-firstboot.sh (block panel-alert-route) as
# /usr/local/lib/wall-panel/panel-alert, the hook point wall-power-button.py
# calls as `panel-alert KEY MESSAGE` (its ALERT_HOOK), off the press path and
# under a hard timeout of its own.
#
# IT INVENTS NO TRANSPORT. It maps the pair onto homehub-alert.sh (SR-085), the
# hub's one alert path, installed BESIDE this file and byte-identical to
# stack/monitoring/homehub-alert.sh (a test compares the two): ntfy over plain
# HTTP on the LAN, a per-key rate limit (one delivery per 30 min), and one
# journal line for every call whatever happened. So a panel alert reaches the
# same topic, in the same format, as every hub alert.
#
# WHERE THE HUB IS: /etc/wall-panel/panel-alert.env, generated by firstboot from
# wall.env (HUB_IP, WALL_ALERT_NTFY_PORT, WALL_ALERT_TOPIC) in the very keys
# homehub-alert.sh reads (LAN_IP, NTFY_PORT, HOMEHUB_ALERT_TOPIC). Absent or
# unusable, the helper journals "ALERT NOT SENT" and exits 4.
#
# The rate-limit stamps live in /var/lib/wall-panel-alert, the calling unit's
# StateDirectory (wall-power-button.service).
#
# Exit: homehub-alert.sh's own (0 delivered, 3 suppressed by the rate limit,
# 4 not delivered, 2 usage), and 4 when the helper itself is missing.
#
# PANEL_ALERT_ENV_FILE and PANEL_ALERT_STATE_DIR exist for the hermetic tests
# (tests/test_wall_power_button.py TC-1329); no unit sets them.
set -u

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
HELPER="$here/homehub-alert.sh"
ENV_FILE="${PANEL_ALERT_ENV_FILE:-/etc/wall-panel/panel-alert.env}"
STATE_DIR="${PANEL_ALERT_STATE_DIR:-/var/lib/wall-panel-alert}"

if [ $# -ne 2 ] || [ -z "$1" ]; then
    printf 'usage: panel-alert KEY MESSAGE\n' >&2
    exit 2
fi
key="$1"
message="$2"
if [ ! -x "$HELPER" ]; then
    printf '%s [panel-alert] ALERT NOT SENT (no %s) [wall-panel.%s]\n' \
        "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$HELPER" "$key"
    exit 4
fi
exec "$HELPER" --key "wall-panel.$key" --priority high --title "Wall panel: $key" \
    --body "$message" --tags "warning,wall-panel" --env-file "$ENV_FILE" \
    --state-dir "$STATE_DIR" --log-tag panel-alert
